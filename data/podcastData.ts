export function resolveLine(line: string, char1Name: string, char2Name: string, topicTag: string): string {
  return line
    .replace(/\{char1\}/g, char1Name)
    .replace(/\{char2\}/g, char2Name)
    .replace(/\{topic\}/g, topicTag);
}

